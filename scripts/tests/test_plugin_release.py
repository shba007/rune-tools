import copy
import hashlib
import importlib.util
import json
from pathlib import Path
import tempfile
import unittest
import subprocess
import sys
from unittest.mock import patch

spec = importlib.util.spec_from_file_location("plugin_release", Path(__file__).parents[1] / "plugin-release.py")
release = importlib.util.module_from_spec(spec)
spec.loader.exec_module(release)
SHA = "a" * 40


class FakeGitHub:
    repo = "owner/tools"

    def __init__(self):
        self.value = None
        self.calls = []
        self.create_error = None
        self.upload_error = None

    def release(self, name):
        self.calls.append(("get", name))
        return copy.deepcopy(self.value)

    def get(self, path):
        return {"sha": SHA}

    def run(self, *args):
        self.calls.append(args)
        if args[:2] == ("release", "create"):
            if self.create_error and not release.collision(self.create_error):
                raise self.create_error
            self.value = {"tag_name": args[2], "body": Path(args[args.index("--notes-file") + 1]).read_text(encoding="utf-8"), "assets": []}
            if self.create_error:
                raise self.create_error
        elif args[:2] == ("release", "upload"):
            if self.upload_error and not release.collision(self.upload_error):
                raise self.upload_error
            path = Path(args[3])
            data = path.read_bytes()
            self.value["assets"].append({"name": path.name, "size": len(data),
                "digest": "sha256:" + hashlib.sha256(data).hexdigest(),
                "browser_download_url": f"https://github.com/{self.repo}/releases/download/{args[2]}/{path.name}"})
            if self.upload_error:
                raise self.upload_error
        else:
            raise AssertionError(args)


class ReleaseTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        folder = self.root / "plugins/rune-filesystem"
        folder.mkdir(parents=True)
        (self.root / "Cargo.toml").write_text('[workspace]\nmembers=["plugins/rune-filesystem"]\n')
        (folder / "Cargo.toml").write_text('[package]\nname="rune-filesystem"\nversion="0.4.2"\ndescription="Bounded reads"\n')
        (folder / "plugin.toml").write_text('[plugin]\nname="rune-filesystem"\nversion="0.4.2"\nexecution_model="wasm"\n')
        self.body = '## rune-filesystem-v0.4.2 - 2026-10-23\n\n- Read selected folders with bounded text and directory results.\n'
        (folder / "CHANGELOG.md").write_text(self.body)
        (self.root / "registry").mkdir()
        (self.root / "registry/index.json").write_text(json.dumps({
            "other": {"latest": "1.0.0", "versions": {"1.0.0": {"url": "original"}}},
            "rune-filesystem": {"latest": "0.4.1", "versions": {"0.4.1": {"url": "original-filesystem"}}}}) + "\n")
        self.plugin = release.plugins(self.root)[0]
        self.assets = self.root / "dist"
        self.assets.mkdir()
        self.payload = self.assets / release.payloads(self.plugin)["wasm"]
        self.payload.write_bytes(b"\0asm-payload")
        self.gh = FakeGitHub()

    def test_real_prefixed_version_preview(self):
        text = (release.ROOT / "plugins/rune-filesystem/CHANGELOG.md").read_text(encoding="utf-8")
        body = release.extract_notes(text, "rune-filesystem", "0.4.1")
        self.assertTrue(body.startswith("## rune-filesystem-v0.4.1"))
        self.assertIn("confine and bound two read-only tools", body)
        self.assertNotIn("## rune-filesystem-v0.4.0", body)

    def test_notes_reject_missing_mismatch_empty_placeholders_and_version_only(self):
        for text in ["", "## other-v0.4.2\n- A useful change\n", "## rune-filesystem-v0.4.1\n- A useful change\n",
                     "## rune-filesystem-v0.4.2\n\n- - -\nChangelog generated by [tool](url).\n",
                     "## rune-filesystem-v0.4.2\n- TODO\n", "## rune-filesystem-v0.4.2\n- chore(version): bump packages\n",
                     "## rune-filesystem-v0.4.2\n- Version bump\n"]:
            with self.subTest(text=text), self.assertRaises(ValueError):
                release.extract_notes(text, "rune-filesystem", "0.4.2")

    def test_duplicate_sections_reject(self):
        with self.assertRaises(ValueError):
            release.extract_notes(self.body + self.body, "rune-filesystem", "0.4.2")

    def test_cli_preview_is_utf8_and_version_mismatch_fails(self):
        command = [sys.executable, str(release.ROOT / "scripts/plugin-release.py"), "notes", "rune-filesystem"]
        result = subprocess.run([*command, "0.4.1"], capture_output=True, encoding="utf-8")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("confine and bound two read-only tools", result.stdout)
        result = subprocess.run([*command, "99.99.99"], capture_output=True, encoding="utf-8")
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("must match", result.stderr)

    def test_matching_section_preserves_substantive_markdown(self):
        self.assertEqual(release.extract_notes(self.body + "\n- - -\n## rune-filesystem-v0.4.1\n- Older fix\n", "rune-filesystem", "0.4.2"), self.body)
        self.assertEqual(release.extract_notes(self.body + "\n- - -\nChangelog generated by [tool](url).\n", "rune-filesystem", "0.4.2"), self.body)

    def test_manifest_version_mismatch_rejects(self):
        (self.plugin["folder"] / "plugin.toml").write_text('[plugin]\nname="rune-filesystem"\nversion="0.4.1"\nexecution_model="wasm"\n')
        with self.assertRaises(ValueError):
            release.plugins(self.root)

    def test_invalid_notes_fail_before_any_remote_operation(self):
        (self.plugin["folder"] / "CHANGELOG.md").write_text("## rune-filesystem-v0.4.2\n- TBD\n")
        with self.assertRaises(ValueError):
            release.publish(self.gh, self.plugin, self.assets, SHA)
        self.assertEqual(self.gh.calls, [])

    def test_missing_payload_fails_before_any_remote_operation(self):
        self.payload.unlink()
        with self.assertRaises(ValueError):
            release.publish(self.gh, self.plugin, self.assets, SHA)
        self.assertEqual(self.gh.calls, [])

    def test_publish_exact_notes_and_identical_retry_does_not_upload_again(self):
        release.publish(self.gh, self.plugin, self.assets, SHA)
        self.assertEqual(self.gh.value["body"], self.body)
        self.assertEqual(len(self.gh.value["assets"]), 2)
        uploads = len([c for c in self.gh.calls if c[:2] == ("release", "upload")])
        release.publish(self.gh, self.plugin, self.assets, SHA)
        self.assertEqual(len([c for c in self.gh.calls if c[:2] == ("release", "upload")]), uploads)

    def test_changed_payload_refuses_overwrite(self):
        release.publish(self.gh, self.plugin, self.assets, SHA)
        self.payload.write_bytes(b"different")
        with self.assertRaisesRegex(ValueError, "refusing overwrite"):
            release.publish(self.gh, self.plugin, self.assets, SHA)

    def test_changed_published_notes_and_wrong_source_refuse(self):
        release.publish(self.gh, self.plugin, self.assets, SHA)
        with patch.object(self.gh, "get", return_value={"sha": "b" * 40}), self.assertRaisesRegex(ValueError, "source commit"):
            release.publish(self.gh, self.plugin, self.assets, SHA)
        self.gh.value["body"] = "Old published notes"
        with self.assertRaisesRegex(ValueError, "refusing to rewrite"):
            release.publish(self.gh, self.plugin, self.assets, SHA)

    def test_creation_and_upload_collisions_are_verified(self):
        self.gh.create_error = release.GitHubError("already_exists")
        self.gh.upload_error = release.GitHubError("already exists")
        release.publish(self.gh, self.plugin, self.assets, SHA)
        self.assertEqual(len(self.gh.value["assets"]), 2)

    def test_permission_and_upload_server_failures_are_not_hidden(self):
        self.gh.create_error = release.GitHubError("HTTP 403")
        with self.assertRaisesRegex(release.GitHubError, "403"):
            release.publish(self.gh, self.plugin, self.assets, SHA)
        self.gh.create_error = None
        self.gh.upload_error = release.GitHubError("HTTP 500")
        with self.assertRaisesRegex(release.GitHubError, "500"):
            release.publish(self.gh, self.plugin, self.assets, SHA)

    def test_only_404_means_release_absent(self):
        gh = release.GitHub("owner/tools")
        with patch.object(gh, "run", side_effect=release.GitHubError("HTTP 404")):
            self.assertIsNone(gh.release("tag"))
        with patch.object(gh, "run", side_effect=release.GitHubError("HTTP 403")), self.assertRaises(release.GitHubError):
            gh.release("tag")

    def test_registry_requires_payloads_and_matching_checksum_sidecars(self):
        with self.assertRaises(ValueError):
            release.registry_entry(self.gh, self.plugin, SHA)
        release.publish(self.gh, self.plugin, self.assets, SHA)
        entry = release.registry_entry(self.gh, self.plugin, SHA)
        self.assertIn(self.payload.name, entry["checksums"])
        self.gh.value["assets"].pop()
        with self.assertRaisesRegex(ValueError, "checksum sidecar"):
            release.registry_entry(self.gh, self.plugin, SHA)

    def test_registry_handoff_preserves_source_and_other_versions(self):
        release.publish(self.gh, self.plugin, self.assets, SHA)
        source = self.root / "registry/index.json"
        before = source.read_bytes()
        output = self.root / "handoff"
        release.registry_handoff(self.gh, SHA, output, self.root)
        self.assertEqual(source.read_bytes(), before)
        new = json.loads((output / "index.json").read_text())
        self.assertEqual(new["other"], json.loads(before)["other"])
        self.assertEqual(new["rune-filesystem"]["latest"], "0.4.2")
        self.assertEqual(new["rune-filesystem"]["versions"]["0.4.1"], json.loads(before)["rune-filesystem"]["versions"]["0.4.1"])
        self.assertIn("+++ b/registry/index.json", (output / "registry.patch").read_text())
        self.assertTrue((output / "release-evidence.json").is_file())

    def test_handoff_cannot_overwrite_source_registry(self):
        with self.assertRaisesRegex(ValueError, "source registry"):
            release.registry_handoff(self.gh, SHA, self.root / "registry", self.root)
        self.assertEqual(self.gh.calls, [])

    def test_generated_registry_patch_passes_read_only_git_apply_check(self):
        release.publish(self.gh, self.plugin, self.assets, SHA)
        source = self.root / "registry/index.json"
        original = source.read_bytes().replace(b"\r\n", b"\n")
        for ending in [b"\n", b"\r\n"]:
            source.write_bytes(original.replace(b"\n", ending))
            output = self.root / "checked-handoff"
            release.registry_handoff(self.gh, SHA, output, self.root)
            # --check only reads the disposable fixture; no apply/index/Git writes.
            result = subprocess.run(["git", "apply", "--check", "--ignore-space-change", "--unsafe-paths", "--directory",
                                     str(self.root), str(output / "registry.patch")],
                                    cwd=release.ROOT, capture_output=True, encoding="utf-8")
            self.assertEqual(result.returncode, 0, f"{ending!r}: {result.stderr}")

    def test_native_registry_urls_remain_compatible_and_require_all_targets(self):
        self.plugin["model"] = "native"
        for name in release.payloads(self.plugin).values():
            (self.assets / name).write_bytes(b"native archive")
        release.publish(self.gh, self.plugin, self.assets, SHA)
        entry = release.registry_entry(self.gh, self.plugin, SHA)
        self.assertEqual(set(entry["native"]), set(release.TARGETS))
        self.assertTrue(all(isinstance(url, str) for url in entry["native"].values()))
        self.assertEqual(len(entry["checksums"]), 4)
        self.gh.value["assets"].pop(0)
        with self.assertRaisesRegex(ValueError, "payload missing"):
            release.registry_entry(self.gh, self.plugin, SHA)


if __name__ == "__main__":
    unittest.main()
