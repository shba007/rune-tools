"""Owner-triggered release tooling. Local notes/validate never publish or change Git.

Requires Python 3.11+. Only publish/registry contact GitHub, using the gh CLI.
No command stages, commits, pushes, or regenerates notes from Git history.
"""
import argparse
import difflib
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tomllib

ROOT = Path(__file__).resolve().parents[1]
TARGETS = {
    "x86_64-unknown-linux-gnu": "tar.gz",
    "aarch64-apple-darwin": "tar.gz",
    "x86_64-apple-darwin": "tar.gz",
    "x86_64-pc-windows-msvc": "zip",
}


def extract_notes(text, name, version):
    """Keep the matching Markdown section, including its prefixed heading."""
    lines = text.splitlines(keepends=True)
    sections = []
    for i, line in enumerate(lines):
        if not line.startswith("## "):
            continue
        tokens = line[3:].split()
        if not tokens:
            continue
        token = tokens[0].strip("[]")
        if token in {version, "v" + version, f"{name}-v{version}"}:
            sections.append(i)
    if len(sections) != 1:
        raise ValueError(f"{name} {version}: expected one matching CHANGELOG section, found {len(sections)}")
    start = sections[0]
    end = next((i for i in range(start + 1, len(lines)) if lines[i].startswith("## ")), len(lines))
    section = lines[start:end]
    footer = next((i for i, line in enumerate(section) if line.startswith("Changelog generated by")), len(section))
    section = section[:footer]
    while section and (not section[-1].strip() or section[-1].strip() in {"- - -", "---"}):
        section.pop()
    body = [line.strip().lstrip("-* ") for line in section[1:]
            if line.strip() and not line.lstrip().startswith("#") and line.strip() not in {"- - -", "---"}
            and not line.startswith("Changelog generated by")]
    placeholders = re.compile(r"\b(todo|tbd|placeholder|coming soon|no changes yet|nothing yet)\b", re.I)
    if any(placeholders.search(line) for line in body):
        raise ValueError(f"{name} {version}: placeholder release notes")
    substantive = [line for line in body if not re.search(r"\b(bump|bumped|bumping)\b.*\b(versions?|packages?)\b|\bversion[- ]bump\b|chore\(version\)", line, re.I)
                   and line.lower() not in {name.lower(), f"{name} v{version}".lower(), f"{name}-v{version}".lower(),
                                            version, f"release {version}", f"release v{version}", f"version {version}"}]
    if not substantive:
        raise ValueError(f"{name} {version}: missing substantive behavior/compatibility notes")
    return "".join(section).rstrip() + "\n"


def plugins(root=ROOT):
    workspace = tomllib.loads((root / "Cargo.toml").read_text(encoding="utf-8"))
    result = []
    for member in workspace["workspace"]["members"]:
        if not member.startswith("plugins/"):
            continue
        folder = root / member
        cargo = tomllib.loads((folder / "Cargo.toml").read_text(encoding="utf-8"))["package"]
        manifest = tomllib.loads((folder / "plugin.toml").read_text(encoding="utf-8"))["plugin"]
        if cargo["name"] != manifest["name"] or cargo["version"] != manifest["version"]:
            raise ValueError(f"{member}: Cargo.toml and plugin.toml name/version must match")
        if manifest["execution_model"] not in {"wasm", "native"}:
            raise ValueError(f"{member}: unsupported execution_model")
        result.append(dict(name=cargo["name"], version=cargo["version"],
                           description=cargo.get("description", ""), model=manifest["execution_model"], folder=folder))
    return result


def notes(plugin):
    return extract_notes((plugin["folder"] / "CHANGELOG.md").read_text(encoding="utf-8"), plugin["name"], plugin["version"])


def tag(plugin):
    return f"{plugin['name']}-v{plugin['version']}"


def payloads(plugin):
    if plugin["model"] == "wasm":
        return {"wasm": f"{plugin['name']}-{plugin['version']}.wasm"}
    return {target: f"{plugin['name']}-native-{plugin['version']}-{target}.{ext}"
            for target, ext in TARGETS.items()}


def pending(root=ROOT):
    registry = json.loads((root / "registry/index.json").read_text(encoding="utf-8"))
    return [p for p in plugins(root) if p["version"] not in registry.get(p["name"], {}).get("versions", {})]


class GitHubError(RuntimeError):
    pass


class GitHub:
    def __init__(self, repo):
        if not re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", repo):
            raise ValueError("Expected --repo owner/repository")
        self.repo = repo

    def run(self, *args):
        result = subprocess.run(["gh", *args], capture_output=True, text=True, encoding="utf-8")
        if result.returncode:
            raise GitHubError(result.stderr.strip() or result.stdout.strip())
        return result.stdout

    def get(self, path):
        return json.loads(self.run("api", f"repos/{self.repo}/{path}"))

    def release(self, release_tag):
        try:
            return self.get(f"releases/tags/{release_tag}")
        except GitHubError as error:
            if "HTTP 404" in str(error):
                return None
            raise


def collision(error):
    return any(text in str(error).lower() for text in ["already_exists", "already exists"])


def verify_release(gh, plugin, release, expected_notes, target):
    if release is None or release.get("tag_name") != tag(plugin) or release.get("draft") or release.get("prerelease"):
        raise ValueError(f"{tag(plugin)}: missing release or unexpected tag/draft/prerelease")
    if (release.get("body") or "").rstrip() != expected_notes.rstrip():
        raise ValueError(f"{tag(plugin)}: existing release notes differ; refusing to rewrite published notes")
    if gh.get(f"commits/{tag(plugin)}")["sha"] != target:
        raise ValueError(f"{tag(plugin)}: tag does not point to the requested source commit")


def asset_matches(asset, digest, size):
    return asset.get("digest") == "sha256:" + digest and asset.get("size") == size


def ensure_asset(gh, plugin, path):
    data = path.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    release = gh.release(tag(plugin))
    existing = next((a for a in release["assets"] if a["name"] == path.name), None)
    if existing is not None:
        if not asset_matches(existing, digest, len(data)):
            raise ValueError(f"{path.name}: existing asset differs or has no verifiable digest; refusing overwrite")
        return
    try:
        gh.run("release", "upload", tag(plugin), str(path), "--repo", gh.repo)
    except GitHubError as error:
        if not collision(error):
            raise
        # Another publisher may have uploaded the same immutable bytes.
    uploaded = next((a for a in gh.release(tag(plugin))["assets"] if a["name"] == path.name), None)
    if uploaded is None or not asset_matches(uploaded, digest, len(data)):
        raise ValueError(f"{path.name}: uploaded asset digest/size verification failed")


def publish(gh, plugin, directory, target):
    body = notes(plugin)  # Validate before any GitHub operation.
    paths = [directory / name for name in payloads(plugin).values()]
    for path in paths:
        if not path.is_file() or path.stat().st_size == 0:
            raise ValueError(f"Missing or empty built payload: {path}")
    release = gh.release(tag(plugin))
    if release is None:
        note_file = directory / f"{tag(plugin)}-notes.md"
        note_file.write_text(body, encoding="utf-8", newline="\n")
        try:
            gh.run("release", "create", tag(plugin), "--repo", gh.repo, "--target", target,
                   "--title", tag(plugin), "--notes-file", str(note_file))
        except GitHubError as error:
            if not collision(error):
                raise
        release = gh.release(tag(plugin))
    verify_release(gh, plugin, release, body, target)
    for path in paths:
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        checksum = path.with_name(path.name + ".sha256")
        checksum.write_text(f"{digest}  {path.name}\n", encoding="ascii", newline="\n")
        ensure_asset(gh, plugin, path)
        ensure_asset(gh, plugin, checksum)


def registry_entry(gh, plugin, target):
    release = gh.release(tag(plugin))
    verify_release(gh, plugin, release, notes(plugin), target)
    assets = {a["name"]: a for a in release["assets"]}
    entry = {"checksums": {}}
    for platform, name in payloads(plugin).items():
        asset = assets.get(name, {})
        digest = asset.get("digest", "")
        if not re.fullmatch(r"sha256:[0-9a-f]{64}", digest) or asset.get("size", 0) <= 0:
            raise ValueError(f"{name}: published payload missing or has no SHA-256 evidence")
        checksum_text = f"{digest[7:]}  {name}\n".encode("ascii")
        checksum = assets.get(name + ".sha256", {})
        if not asset_matches(checksum, hashlib.sha256(checksum_text).hexdigest(), len(checksum_text)):
            raise ValueError(f"{name}: checksum sidecar missing or mismatched")
        url = f"https://github.com/{gh.repo}/releases/download/{tag(plugin)}/{name}"
        if asset.get("browser_download_url") != url or checksum.get("browser_download_url") != url + ".sha256":
            raise ValueError(f"{name}: unexpected release download URL")
        if platform == "wasm":
            entry["url"] = url
        else:
            entry.setdefault("native", {})[platform] = url
        entry["checksums"][name] = {"sha256": digest[7:], "url": url + ".sha256"}
    return entry


def registry_handoff(gh, target, output, root=ROOT):
    if (output / "index.json").resolve() == (root / "registry/index.json").resolve():
        raise ValueError("Registry handoff output must not overwrite the source registry")
    original = (root / "registry/index.json").read_text(encoding="utf-8")
    registry = json.loads(original)
    evidence = {}
    for plugin in pending(root):
        version = registry_entry(gh, plugin, target)
        entry = registry.setdefault(plugin["name"], {"versions": {}})
        entry["versions"][plugin["version"]] = version
        entry["latest"] = plugin["version"]
        entry["description"] = plugin["description"]
        evidence[tag(plugin)] = version
    # No changes means no reformatting or synthetic registry update.
    rendered = json.dumps(registry, indent=2, sort_keys=True, ensure_ascii=False) + "\n" if evidence else original
    patch = "".join(difflib.unified_diff(original.splitlines(keepends=True), rendered.splitlines(keepends=True),
                                       fromfile="a/registry/index.json", tofile="b/registry/index.json"))
    output.mkdir(parents=True, exist_ok=True)
    (output / "index.json").write_text(rendered, encoding="utf-8", newline="\n")
    (output / "registry.patch").write_text(patch, encoding="utf-8", newline="\n")
    (output / "release-evidence.json").write_text(json.dumps({"source_commit": target, "releases": evidence}, indent=2) + "\n", encoding="utf-8")
    (output / "README.txt").write_text(
        "Owner action: download this registry-handoff artifact after publication succeeds.\n"
        "In an up-to-date main checkout, review release-evidence.json and registry.patch.\n"
        "If nonempty, run git apply --check --ignore-space-change <path>/registry.patch, then git apply --ignore-space-change <path>/registry.patch.\n"
        "Review the resulting diff, commit registry/index.json and push main yourself.\n"
        "Do not overwrite concurrent registry changes. A conflicting patch requires review.\n"
        "The existing registry stays usable; new versions enter package discovery after your registry push.\n"
        "An empty patch requires no source commit. This tooling never commits or pushes.\n", encoding="utf-8")
    return evidence


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    preview = sub.add_parser("notes")
    preview.add_argument("plugin")
    preview.add_argument("version")
    preview.add_argument("--output", type=Path)
    validate = sub.add_parser("validate")
    validate.add_argument("--output", type=Path, required=True)
    validate.add_argument("--github-output", type=Path)
    release = sub.add_parser("publish")
    release.add_argument("plugin")
    release.add_argument("version")
    release.add_argument("--assets-dir", type=Path, required=True)
    for command in [release, sub.add_parser("registry")]:
        command.add_argument("--repo", required=True)
        command.add_argument("--target", required=True)
    sub.choices["registry"].add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    if args.command in {"publish", "registry"} and not re.fullmatch(r"[0-9a-fA-F]{40}", args.target):
        raise ValueError("--target must be the full release source commit SHA")
    if args.command in {"notes", "publish"}:
        plugin = next((p for p in plugins() if p["name"] == args.plugin), None)
        if plugin is None or plugin["version"] != args.version:
            raise ValueError("Requested plugin/version must match its current Cargo.toml and plugin.toml")
        if args.command == "notes":
            body = notes(plugin)
            if args.output:
                if args.output.resolve() == (plugin["folder"] / "CHANGELOG.md").resolve():
                    raise ValueError("Notes preview must not overwrite its source CHANGELOG")
                args.output.parent.mkdir(parents=True, exist_ok=True)
                args.output.write_text(body, encoding="utf-8", newline="\n")
            else:
                print(body, end="")
        else:
            publish(GitHub(args.repo), plugin, args.assets_dir, args.target)
    elif args.command == "validate":
        candidates = pending()
        validated = [(p, notes(p)) for p in candidates]  # All notes must pass first.
        args.output.mkdir(parents=True, exist_ok=True)
        for plugin, body in validated:
            (args.output / (tag(plugin) + ".md")).write_text(body, encoding="utf-8", newline="\n")
        values = {"release_matrix": json.dumps({"include": [{"name": p["name"], "version": p["version"]} for p in candidates]}),
                  "has_releases": str(bool(candidates)).lower()}
        rendered = "".join(f"{key}={value}\n" for key, value in values.items())
        if args.github_output:
            with args.github_output.open("a", encoding="utf-8") as output:
                output.write(rendered)
        print(rendered, end="")
    else:
        evidence = registry_handoff(GitHub(args.repo), args.target, args.output)
        print(f"Registry handoff: {len(evidence)} release(s); source index unchanged")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    sys.stderr.reconfigure(encoding="utf-8")
    try:
        main()
    except (ValueError, OSError, GitHubError) as error:
        print(f"Release validation failed: {error}", file=sys.stderr)
        sys.exit(1)
