//! Deterministic per-plugin preparation. Git access is read-only; --apply only writes files.
use semver::Version;
use serde::{Deserialize, Serialize};
use serde_json::{Value, json};
use std::{collections::BTreeSet, fs, path::Path, process::Command};
use toml_edit::{DocumentMut, value};
pub type Result<T> = std::result::Result<T, Box<dyn std::error::Error>>;

pub fn git(root: &Path, args: &[&str]) -> Result<String> {
    let out = Command::new("git").current_dir(root).args(args).output()?;
    if !out.status.success() {
        return Err(String::from_utf8_lossy(&out.stderr).into_owned().into());
    }
    Ok(String::from_utf8(out.stdout)?.trim_end().into())
}
#[derive(Clone, Debug)]
pub struct Plugin {
    pub name: String,
    pub version: String,
    pub model: String,
    pub folder: String,
    pub description: String,
}
pub fn plugins(root: &Path) -> Result<Vec<Plugin>> {
    let workspace: toml::Value = toml::from_str(&fs::read_to_string(root.join("Cargo.toml"))?)?;
    workspace["workspace"]["members"]
        .as_array()
        .ok_or("workspace members missing")?
        .iter()
        .filter_map(|m| m.as_str().filter(|s| s.starts_with("plugins/")))
        .map(|folder| {
            let cargo: toml::Value =
                toml::from_str(&fs::read_to_string(root.join(folder).join("Cargo.toml"))?)?;
            let manifest: toml::Value =
                toml::from_str(&fs::read_to_string(root.join(folder).join("plugin.toml"))?)?;
            let p = &cargo["package"];
            let m = &manifest["plugin"];
            if p["name"] != m["name"] || p["version"] != m["version"] {
                return Err(format!("{folder}: Cargo/plugin manifest mismatch").into());
            }
            let model = m["execution_model"]
                .as_str()
                .ok_or("execution_model missing")?;
            if !matches!(model, "wasm" | "native") {
                return Err("unsupported execution model".into());
            }
            Ok(Plugin {
                name: p["name"].as_str().ok_or("name missing")?.into(),
                version: p["version"].as_str().ok_or("version missing")?.into(),
                model: model.into(),
                folder: folder.into(),
                description: p
                    .get("description")
                    .and_then(|v| v.as_str())
                    .unwrap_or_default()
                    .into(),
            })
        })
        .collect()
}
pub fn private_text(text: &str) -> bool {
    let lower = text.to_ascii_lowercase();
    let words: Vec<_> = lower
        .split(|c: char| !c.is_alphanumeric())
        .filter(|s| !s.is_empty())
        .collect();
    words.iter().any(|w| {
        matches!(
            *w,
            "cycle" | "milestone" | "todo" | "tbd" | "placeholder" | "unreleased"
        )
    }) || words.iter().any(|w| {
        let i = w.find(|c: char| c.is_ascii_digit()).unwrap_or(w.len());
        let (p, n) = w.split_at(i);
        matches!(p, "m" | "k" | "l" | "r" | "inf" | "kf" | "wp")
            && !n.is_empty()
            && n.chars().all(|c| c.is_ascii_digit())
    }) || words.windows(2).any(|w| {
        matches!(w[0], "m" | "k" | "l" | "r" | "inf" | "kf" | "wp")
            && w[1].chars().all(|c| c.is_ascii_digit())
    }) || ["coming soon", "no changes yet", "nothing yet"]
        .iter()
        .any(|s| lower.contains(s))
}
pub fn notes(text: &str, name: &str, version: &str) -> Result<String> {
    let lines: Vec<_> = text.lines().collect();
    let indices: Vec<_> = lines
        .iter()
        .enumerate()
        .filter_map(|(i, l)| {
            let token = l
                .strip_prefix("## ")?
                .split_whitespace()
                .next()?
                .trim_matches(['[', ']']);
            (token == version
                || token == format!("v{version}")
                || token == format!("{name}-v{version}"))
            .then_some(i)
        })
        .collect();
    if indices.len() != 1 {
        return Err(format!(
            "{name} {version}: expected one matching CHANGELOG section, found {}",
            indices.len()
        )
        .into());
    }
    let start = indices[0];
    let end = (start + 1..lines.len())
        .find(|&i| lines[i].starts_with("## ") || lines[i].starts_with("Changelog generated by"))
        .unwrap_or(lines.len());
    let section = lines[start..end].join("\n");
    let section = section
        .trim_end()
        .trim_end_matches("- - -")
        .trim_end_matches("---")
        .trim_end();
    let body: Vec<_> = section
        .lines()
        .skip(1)
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with('#') && !matches!(*l, "---" | "- - -"))
        .collect();
    let substantive = body.iter().any(|line| {
        let line = line
            .trim_start_matches(['-', '*', ' '])
            .to_ascii_lowercase();
        let bare = [
            name.to_ascii_lowercase(),
            version.to_string(),
            format!("v{version}"),
            format!("{name} v{version}"),
            format!("{name}-v{version}"),
            format!("release {version}"),
            format!("release v{version}"),
            format!("version {version}"),
        ];
        let bump = (line.contains("bump")
            && (line.contains("version") || line.contains("package")))
            || line.contains("version-bump")
            || line.contains("chore(version)");
        !line.is_empty() && !bare.contains(&line) && !bump
    });
    if !substantive || private_text(&body.join("\n")) {
        return Err(format!(
            "{name} {version}: empty, placeholder, internal or version-only release notes"
        )
        .into());
    }
    Ok(format!("{section}\n"))
}
pub fn plugin_notes(root: &Path, p: &Plugin) -> Result<String> {
    notes(
        &fs::read_to_string(root.join(&p.folder).join("CHANGELOG.md"))?,
        &p.name,
        &p.version,
    )
}
pub fn registry(root: &Path) -> Result<Value> {
    Ok(serde_json::from_str(&fs::read_to_string(
        root.join("registry/index.json"),
    )?)?)
}
pub fn pending(root: &Path) -> Result<Vec<Plugin>> {
    let r = registry(root)?;
    Ok(plugins(root)?
        .into_iter()
        .filter(|p| r[&p.name]["versions"].get(&p.version).is_none())
        .collect())
}
pub fn output(key: &str, value: impl std::fmt::Display) -> Result<()> {
    use std::io::Write;
    println!("{key}={value}");
    if let Some(path) = std::env::var_os("GITHUB_OUTPUT") {
        writeln!(
            fs::OpenOptions::new()
                .append(true)
                .create(true)
                .open(path)?,
            "{key}={value}"
        )?;
    }
    Ok(())
}

#[derive(Clone, Debug)]
pub struct Change {
    pub message: String,
    pub paths: Vec<String>,
}
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct Prepared {
    pub name: String,
    pub version: String,
    pub notes: String,
}
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct State {
    pub source_head: String,
    pub releases: Vec<Prepared>,
}
fn runtime_path(path: &str) -> bool {
    !(path.ends_with(".md")
        || path.ends_with("mcp.json")
        || path.contains("/tests/")
        || path.ends_with("/.env")
        || path.contains("/examples/"))
}
/// Follow local workspace dependencies, including native feature/target dependencies.
fn depends(root: &Path, folder: &str, changed: &str, seen: &mut BTreeSet<String>) -> Result<bool> {
    if folder == changed {
        return Ok(true);
    }
    if !seen.insert(folder.into()) {
        return Ok(false);
    }
    let doc: toml::Value =
        toml::from_str(&fs::read_to_string(root.join(folder).join("Cargo.toml"))?)?;
    fn names(v: &toml::Value, out: &mut BTreeSet<String>) {
        if let Some(t) = v.as_table() {
            for (k, v) in t {
                if matches!(k.as_str(), "dependencies" | "build-dependencies") {
                    if let Some(t) = v.as_table() {
                        out.extend(t.keys().cloned());
                    }
                } else if k != "dev-dependencies" {
                    names(v, out)
                }
            }
        }
    }
    let mut deps = BTreeSet::new();
    names(&doc, &mut deps);
    for dep in deps {
        let dep_folder = format!("crates/{dep}");
        if root.join(&dep_folder).join("Cargo.toml").exists()
            && depends(root, &dep_folder, changed, seen)?
        {
            return Ok(true);
        }
    }
    Ok(false)
}
pub fn affected(root: &Path, p: &Plugin, paths: &[String]) -> Result<bool> {
    let runtime: Vec<_> = paths.iter().filter(|s| runtime_path(s)).collect();
    for path in &runtime {
        if path.starts_with(&format!("{}/", p.folder)) {
            return Ok(true);
        }
        if path.starts_with("crates/") {
            let parts: Vec<_> = path.split('/').collect();
            if parts.len() > 2
                && depends(
                    root,
                    &p.folder,
                    &format!("crates/{}", parts[1]),
                    &mut BTreeSet::new(),
                )?
            {
                return Ok(true);
            }
        }
    }
    // Root dependency/lock changes conservatively affect all consumers, except xtask-only updates.
    let root_changed = runtime
        .iter()
        .any(|p| matches!(p.as_str(), "Cargo.toml" | "Cargo.lock"));
    let xtask_only = runtime
        .iter()
        .filter(|p| {
            p.starts_with("plugins/")
                || p.starts_with("crates/")
                || matches!(p.as_str(), "Cargo.toml" | "Cargo.lock")
                || p.starts_with("xtask/")
        })
        .all(|p| p.starts_with("xtask/") || matches!(p.as_str(), "Cargo.lock"));
    Ok(root_changed && !xtask_only)
}
pub fn plan(root: &Path, changes: &[Change], source_head: String) -> Result<State> {
    let registry = published_registry(root)?;
    let mut releases = vec![];
    for p in plugins(root)? {
        let mut entries = BTreeSet::new();
        let mut level = 0;
        for change in changes {
            if !affected(root, &p, &change.paths)? {
                continue;
            }
            let Ok(commit) = git_conventional::Commit::parse(&change.message) else {
                continue;
            };
            let kind = commit.type_().to_string();
            let scope = commit.scope().map(|s| s.to_string());
            let description = commit.description().to_ascii_lowercase();
            if (kind == "ci" && scope.as_deref() == Some("release"))
                || matches!(
                    description.as_str(),
                    "bump packages" | "bump versions" | "update version"
                )
                || description.starts_with("bump version to ")
                || scope.as_deref() == Some("registry")
                || scope.as_deref() == Some("version")
                || commit
                    .description()
                    .to_ascii_lowercase()
                    .contains("apply code fixes")
            {
                continue;
            }
            if private_text(commit.description()) {
                return Err(format!(
                    "{}: reviewed commit needs a public behavior description",
                    p.name
                )
                .into());
            }
            level = level.max(if commit.breaking() {
                3
            } else if kind == "feat" {
                2
            } else {
                1
            });
            let group = if commit.breaking() {
                "Compatibility"
            } else {
                match kind.as_str() {
                    "feat" => "Features",
                    "fix" => "Fixes",
                    "perf" => "Performance",
                    _ => "Maintenance",
                }
            };
            entries.insert(format!("- {group}: {}", commit.description()));
            if let Some(migration) = commit.breaking_description() {
                if private_text(migration) {
                    return Err("Breaking change migration must use public wording".into());
                }
                entries.insert(format!(
                    "- Migration: {}",
                    migration.split_whitespace().collect::<Vec<_>>().join(" ")
                ));
            }
        }
        if level == 0 {
            continue;
        }
        let mut v = Version::parse(&p.version)?;
        if level == 3 && v.major > 0 {
            v.major += 1;
            v.minor = 0;
            v.patch = 0;
        } else if level >= 2 {
            v.minor += 1;
            v.patch = 0;
        } else {
            v.patch += 1;
        }
        v.pre = semver::Prerelease::EMPTY;
        v.build = semver::BuildMetadata::EMPTY;
        // Preserve substantive prepared-but-unpublished functionality when another batch arrives.
        if registry[&p.name]["versions"].get(&p.version).is_none() {
            for l in plugin_notes(root, &p)?
                .lines()
                .skip(1)
                .filter(|l| l.starts_with("- "))
            {
                entries.insert(l.into());
            }
        }
        let version = v.to_string();
        let body = format!(
            "## {}-v{}\n\n{}\n",
            p.name,
            version,
            entries.into_iter().collect::<Vec<_>>().join("\n")
        );
        notes(&body, &p.name, &version)?;
        releases.push(Prepared {
            name: p.name,
            version,
            notes: body,
        });
    }
    Ok(State {
        source_head,
        releases,
    })
}
pub fn repository_plan(root: &Path) -> Result<State> {
    let head = git(root, &["rev-parse", "HEAD"])?;
    let state = root.join(".release/prepared.json");
    let base = if state.exists() {
        let s: State = serde_json::from_str(&fs::read_to_string(state)?)?;
        git(
            root,
            &["merge-base", "--is-ancestor", &s.source_head, "HEAD"],
        )?;
        s.source_head
    } else {
        git(root, &["merge-base", "origin/main", "HEAD"])?
    };
    let hashes = git(
        root,
        &[
            "rev-list",
            "--reverse",
            "--no-merges",
            &format!("{base}..HEAD"),
        ],
    )?;
    let mut changes = vec![];
    for hash in hashes.lines() {
        let message = git(root, &["show", "-s", "--format=%B", hash])?;
        let paths = git(
            root,
            &["diff-tree", "--no-commit-id", "--name-only", "-r", hash],
        )?
        .lines()
        .map(str::to_owned)
        .collect();
        changes.push(Change { message, paths });
    }
    plan(root, &changes, head)
}
pub fn apply(root: &Path, state: &State) -> Result<()> {
    // Caller authorizes file writes. Never stages, commits, pushes or installs hooks.
    let all = plugins(root)?;
    for release in &state.releases {
        let p = all
            .iter()
            .find(|p| p.name == release.name)
            .ok_or("unknown prepared plugin")?;
        if p.version == release.version {
            if plugin_notes(root, p)? != release.notes {
                return Err("prepared version already exists with different notes".into());
            }
            continue;
        }
        let changelog = root.join(&p.folder).join("CHANGELOG.md");
        let old = fs::read_to_string(&changelog)?;
        for (file, table) in [("Cargo.toml", "package"), ("plugin.toml", "plugin")] {
            let path = root.join(&p.folder).join(file);
            let mut doc = fs::read_to_string(&path)?.parse::<DocumentMut>()?;
            doc[table]["version"] = value(&release.version);
            fs::write(path, doc.to_string())?;
        }
        let offset = old.find("\n## ").map(|i| i + 1).unwrap_or(old.len());
        fs::write(
            changelog,
            format!("{}{}\n{}", &old[..offset], release.notes, &old[offset..]),
        )?;
    }
    fs::create_dir_all(root.join(".release"))?;
    let mut recorded = state.clone();
    let state_path = root.join(".release/prepared.json");
    if state_path.exists() {
        let previous: State = serde_json::from_str(&fs::read_to_string(&state_path)?)?;
        let published = published_registry(root)?;
        for r in previous.releases {
            if !recorded.releases.iter().any(|p| p.name == r.name)
                && published[&r.name]["versions"].get(&r.version).is_none()
            {
                recorded.releases.push(r);
            }
        }
    }
    fs::write(state_path, serde_json::to_string_pretty(&recorded)? + "\n")?;
    let status = Command::new("cargo")
        .current_dir(root)
        .args([
            "metadata",
            "--offline",
            "--no-deps",
            "--format-version",
            "1",
        ])
        .stdout(std::process::Stdio::null())
        .status()?;
    if !status.success() {
        return Err("lockfile refresh failed".into());
    }
    Ok(())
}
pub fn command(args: &[String]) -> Result<()> {
    let root = Path::new(".");
    match args.first().map(String::as_str) {
        Some("prepare") => {
            let mut write=false;
            let mut summary_file=None;
            let mut options=args.iter().skip(1);
            while let Some(option)=options.next() {
                match option.as_str() {
                    "--apply"=>write=true,
                    "--summary"=>summary_file=Some(options.next().ok_or("--summary needs a file")?),
                    _=>return Err(format!("unknown preparation option: {option}").into())
                }
            }
            let state=repository_plan(root)?;
            let summary=state.releases.iter().map(|r|format!("### {} {}\n\n{}",r.name,r.version,r.notes)).collect::<Vec<_>>().join("\n");
            if summary.is_empty(){println!("No releasable changes; no release PR needed.");}else{println!("{summary}");}
            if write && !state.releases.is_empty(){apply(root,&state)?;}
            if let Some(file)=summary_file {fs::write(file,summary)?;}
            output("prepared",!state.releases.is_empty())?;
        }
        Some("example")=>{
            let shared=args.get(1).is_some_and(|a|a=="--shared");
            if args.len()>1 && (!shared || args.len()!=2){return Err("example [--shared]".into())}
            let change=if shared {
                Change{message:"fix: preserve serialized tool annotation compatibility".into(),paths:vec!["crates/rune-pdk/src/lib.rs".into()]}
            }else{
                Change{message:"fix(filesystem): report confined file read errors clearly".into(),paths:vec!["plugins/rune-filesystem/src/operations.rs".into()]}
            };
            for p in plan(root,&[change],"example-only".into())?.releases {println!("{}",p.notes);}
        }
        Some("notes") if args.len()==3=>{
            let p=plugins(root)?.into_iter().find(|p|p.name==args[1] && p.version==args[2]).ok_or("plugin/version must match current manifests")?;
            print!("{}",plugin_notes(root,&p)?);
        }
        Some("validate")=>{
            if args.len()!=1 && !(args.len()==3 && args[1]=="--output"){return Err("validate [--output DIR]".into())}
            let all=pending(root)?;
            let validated:Vec<_>=all.iter().map(|p|Ok((p,plugin_notes(root,p)?))).collect::<Result<_>>()?;
            if let Some(dir)=args.get(2) {
                fs::create_dir_all(dir)?;
                for(p,body)in validated {fs::write(Path::new(dir).join(format!("{}-v{}.md",p.name,p.version)),body)?;}
            }
            output("release_matrix",json!({"include":all.iter().map(|p|json!({"name":p.name,"version":p.version})).collect::<Vec<_>>()}))?;
            output("has_releases",!all.is_empty())?;
        }
        _=>return Err("expected prepare [--apply] [--summary FILE], example [--shared], notes PLUGIN VERSION, or validate [--output DIR]".into())
    }
    Ok(())
}
pub fn verify_promotion(root: &Path) -> Result<()> {
    let pending = pending(root)?;
    if pending.is_empty() {
        return Ok(());
    }
    let state: State =
        serde_json::from_str(&fs::read_to_string(root.join(".release/prepared.json"))?)?;
    git(
        root,
        &["merge-base", "--is-ancestor", &state.source_head, "HEAD"],
    )?;
    if !repository_plan(root)?.releases.is_empty() {
        return Err(
            "unprepared packaged changes remain; merge preparation before promoting".into(),
        );
    }
    for p in pending {
        let r = state
            .releases
            .iter()
            .find(|r| r.name == p.name && r.version == p.version)
            .ok_or_else(|| {
                format!(
                    "{} {} missing from prepared release state",
                    p.name, p.version
                )
            })?;
        if plugin_notes(root, &p)? != r.notes {
            return Err("prepared changelog differs from reviewed release state".into());
        }
    }
    // Promotion must retain reviewed develop ancestry; squash/rebase promotions are rejected.
    git(root, &["rev-parse", "--verify", "HEAD^2"])?;
    Ok(())
}
/// main owns artifact-backed registry updates; develop need not receive a bookkeeping merge first.
fn published_registry(root: &Path) -> Result<Value> {
    let mut current = registry(root)?;
    if root.join(".git").exists() {
        let main: Value =
            serde_json::from_str(&git(root, &["show", "origin/main:registry/index.json"])?)?;
        for (name, entry) in main.as_object().ok_or("main registry must be an object")? {
            for (version, metadata) in entry["versions"]
                .as_object()
                .ok_or("registry versions missing")?
            {
                current[name]["versions"][version] = metadata.clone();
            }
        }
    }
    Ok(current)
}

